#!/usr/bin/env node
/* global __dirname */
// The colour of the top of each bundled photo, for Sveip's head band (user
// 2026-11-18: the band under the filter bar takes the photo's colour, as the
// reference does, instead of one fixed dark).
//
//   node scripts/build-image-tints.js
//
// Reads every photo the manifest lists (its full file, or a portrait's small
// file) and writes src/fixtures/imageTints.generated.ts: one "#rrggbb" per
// photo, the average of its top fifth. Reads only; no photo is re-encoded.
// Needs ffmpeg on PATH. Re-run after adding or replacing a photo.
const { execFileSync } = require("child_process");
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const DIRS = ["library", "swipe"];
const OUT = path.join(ROOT, "src", "fixtures", "imageTints.generated.ts");

/** Average colour of the top 20 % of the image, as #rrggbb. */
function topTint(file) {
  const raw = execFileSync(
    "ffmpeg",
    [
      "-v",
      "error",
      "-i",
      file,
      "-vf",
      "crop=iw:ih*0.2:0:0,scale=1:1:flags=area",
      "-frames:v",
      "1",
      "-f",
      "rawvideo",
      "-pix_fmt",
      "rgb24",
      "-",
    ],
    { stdio: ["ignore", "pipe", "pipe"] },
  );
  if (raw.length < 3) throw new Error(`no pixel for ${file}`);
  return (
    "#" +
    [raw[0], raw[1], raw[2]]
      .map((v) => v.toString(16).padStart(2, "0"))
      .join("")
  );
}

function names(dir) {
  const set = new Set(
    fs
      .readdirSync(path.join(ROOT, "assets", dir))
      .filter((f) => f.endsWith(".webp"))
      .map((f) => f.replace(/(-sm)?\.webp$/, "")),
  );
  return [...set].sort();
}

function fileFor(dir, n) {
  const full = path.join(ROOT, "assets", dir, `${n}.webp`);
  return fs.existsSync(full)
    ? full
    : path.join(ROOT, "assets", dir, `${n}-sm.webp`);
}

async function main() {
  const rows = [];
  for (const dir of DIRS)
    for (const n of names(dir))
      rows.push(`  "${dir}/${n}": "${topTint(fileFor(dir, n))}",`);
  const text = [
    "// GENERATED by scripts/build-image-tints.js — do not edit by hand.",
    "/** Average colour of the top fifth of each bundled photo, keyed `<dir>/<name>`. */",
    "export const TOP_TINT: Record<string, string> = {",
    ...rows,
    "};",
    "",
  ].join("\n");
  const prettier = require("prettier");
  const options = (await prettier.resolveConfig(OUT)) ?? {};
  fs.writeFileSync(
    OUT,
    await prettier.format(text, { ...options, filepath: OUT }),
  );
  console.log(`wrote ${path.relative(ROOT, OUT)} (${rows.length} photos)`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
