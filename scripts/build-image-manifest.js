#!/usr/bin/env node
/* global __dirname */
// Bundled photo pipeline (Phase 12 H0b, founder: "a lot of images take too
// long to load").
//
//   node scripts/build-image-manifest.js --convert   # JPEG → WebP pair, then manifest
//   node scripts/build-image-manifest.js             # manifest only
//
// --convert: every `assets/{library,swipe}/*.jpg` becomes
//   <name>.webp     long edge ≤ 1080 px (galleries, cards, photo viewer);
//                   Sveip photos keep 1350 px (full-screen cards)
//   <name>-sm.webp  long edge ≤ 480 px (rails, thumbnails, rows); portraits
//                   (person-*) ≤ 256 px
// at WebP quality 75, and the JPEG is deleted (the originals stay in git
// history). Needs ffmpeg with libwebp on PATH.
//
// Portraits (person-*) get the small file only (2026-11-10, "Optimize the
// images"): a face is only ever drawn by Avatar, at most 88 dp, which always
// loads the ≤256 px file, so the full-size copy was never read. Their FULL
// entry points at the small file, so any lookup still resolves.
//
// Manifest: writes src/fixtures/imageAssets.generated.ts with static require()
// maps (Metro needs literal paths) for both sizes plus a tiny blurred preview
// per photo (16 px WebP as a data URI) that expo-image paints as `placeholder`
// while the real file decodes. Re-run after adding or replacing a photo.
const { execFileSync } = require("child_process");
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const DIRS = ["library", "swipe"];
const OUT = path.join(ROOT, "src", "fixtures", "imageAssets.generated.ts");

function ffmpeg(args) {
  execFileSync("ffmpeg", ["-v", "error", "-y", ...args], { stdio: "pipe" });
}

/** A photo with no full-size file (see the header). */
function smallOnly(name) {
  return name.startsWith("person-");
}

/** Long edge ≤ max, aspect kept, never upscaled. */
function fit(max) {
  return `scale=w='min(${max},iw)':h='min(${max},ih)':force_original_aspect_ratio=decrease`;
}

function convert(dir) {
  const abs = path.join(ROOT, "assets", dir);
  for (const file of fs.readdirSync(abs).filter((f) => f.endsWith(".jpg"))) {
    const name = file.slice(0, -4);
    const src = path.join(abs, file);
    const small = name.startsWith("person-") ? 256 : 480;
    const full = dir === "swipe" ? 1350 : 1080;
    if (!smallOnly(name))
      ffmpeg([
        "-i",
        src,
        "-vf",
        fit(full),
        "-c:v",
        "libwebp",
        "-quality",
        "75",
        "-compression_level",
        "6",
        path.join(abs, `${name}.webp`),
      ]);
    ffmpeg([
      "-i",
      src,
      "-vf",
      fit(small),
      "-c:v",
      "libwebp",
      "-quality",
      "75",
      "-compression_level",
      "6",
      path.join(abs, `${name}-sm.webp`),
    ]);
    fs.unlinkSync(src);
    console.log(`converted ${dir}/${file}`);
  }
}

/** 16 px wide WebP of the photo, base64 data URI (~100–250 bytes). */
function placeholder(file) {
  const tmp = path.join(require("os").tmpdir(), `tp-lqip-${process.pid}.webp`);
  ffmpeg([
    "-i",
    file,
    "-vf",
    "scale=16:-2",
    "-c:v",
    "libwebp",
    "-quality",
    "40",
    tmp,
  ]);
  const data = fs.readFileSync(tmp).toString("base64");
  fs.unlinkSync(tmp);
  return `data:image/webp;base64,${data}`;
}

/** Every photo name in a folder: its full file, or its small file alone. */
function names(dir) {
  const set = new Set(
    fs
      .readdirSync(path.join(ROOT, "assets", dir))
      .filter((f) => f.endsWith(".webp"))
      .map((f) => f.replace(/(-sm)?\.webp$/, "")),
  );
  return [...set].sort();
}

/** The full-size file of a photo, or its small file when it has none. */
function fullFile(dir, n) {
  const full = path.join(ROOT, "assets", dir, `${n}.webp`);
  if (fs.existsSync(full)) return `${n}.webp`;
  if (!smallOnly(n)) throw new Error(`missing assets/${dir}/${n}.webp`);
  return `${n}-sm.webp`;
}

async function manifest() {
  const lines = [
    "// GENERATED by scripts/build-image-manifest.js — do not edit by hand.",
    "// Bundled photos (MOCK demo art, see images.ts): full ≤1080 px, small ≤480 px",
    "// (portraits 256 px), and a 16 px blurred preview per photo for expo-image.",
    'import type { ImageSourcePropType } from "react-native";',
    "",
  ];
  const placeholders = [];
  for (const dir of DIRS) {
    const list = names(dir);
    const id = dir.toUpperCase();
    lines.push(`export const ${id}_FULL = {`);
    for (const n of list)
      lines.push(
        `  "${n}": require("../../assets/${dir}/${fullFile(dir, n)}"),`,
      );
    lines.push("} as const;", "");
    lines.push(
      `export const ${id}_SMALL: Record<keyof typeof ${id}_FULL, ImageSourcePropType> = {`,
    );
    for (const n of list) {
      if (!fs.existsSync(path.join(ROOT, "assets", dir, `${n}-sm.webp`)))
        throw new Error(`missing assets/${dir}/${n}-sm.webp`);
      lines.push(`  "${n}": require("../../assets/${dir}/${n}-sm.webp"),`);
    }
    lines.push("};", "");
    for (const n of list)
      placeholders.push(
        `  "${dir}/${n}": "${placeholder(path.join(ROOT, "assets", dir, fullFile(dir, n)))}",`,
      );
  }
  lines.push(
    "/** Blurred 16 px preview per photo, keyed `<dir>/<name>`. */",
    "export const PLACEHOLDER: Record<string, string> = {",
    ...placeholders,
    "};",
    "",
  );
  // Formatted like the rest of the repo, so `prettier --check .` stays green.
  const prettier = require("prettier");
  const options = (await prettier.resolveConfig(OUT)) ?? {};
  const text = await prettier.format(lines.join("\n"), {
    ...options,
    filepath: OUT,
  });
  fs.writeFileSync(OUT, text);
  console.log(`wrote ${path.relative(ROOT, OUT)}`);
}

if (process.argv.includes("--convert")) DIRS.forEach(convert);
manifest().catch((e) => {
  console.error(e);
  process.exit(1);
});
